"""Render examples/*.md into a static gallery for GitHub Pages (site/).

Raw HTML in reports is disabled (markdown-it html=False), so model output
cannot inject scripts into the page.
"""

import html
import json
import pathlib

from markdown_it import MarkdownIt

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "examples"
OUT = ROOT / "site"
md = MarkdownIt("commonmark", {"html": False, "linkify": False}).enable("table")

CSS = """body{font-family:system-ui,sans-serif;max-width:860px;margin:2rem auto;padding:0 1rem;
line-height:1.6;color:#e5e7eb;background:#0b1020}a{color:#67e8f9}code{background:#1f2937}
.card{border:1px solid #334155;border-radius:8px;padding:1rem;margin:1rem 0}
.meta{color:#94a3b8;font-size:.9rem}"""


def page(title, body):
    return (f"<!doctype html><html lang=en><meta charset=utf-8><meta name=viewport "
            f"content='width=device-width,initial-scale=1'><title>{html.escape(title)}</title>"
            f"<style>{CSS}</style><body>{body}</body></html>")


def main():
    OUT.mkdir(exist_ok=True)
    cards = []
    for f in sorted(SRC.glob("*.md")):
        stats_f = f.with_suffix(".stats.json")
        stats = json.loads(stats_f.read_text()) if stats_f.exists() else {}
        topic = stats.get("topic", f.stem)
        meta = (f"model: {stats.get('model', 'qwen2.5:7b')} &middot; runner: "
                f"{html.escape(str(stats.get('runner', 'local')))} &middot; sources: "
                f"{stats.get('sources_total', '?')} found, {len(stats.get('cited', []))} cited "
                f"&middot; uncited paragraphs: {stats.get('uncited_paragraphs', '?')} &middot; "
                f"{stats.get('seconds', '?')} s")
        body = (f"<p><a href='index.html'>&larr; All reports</a></p><p class=meta>{meta}</p>"
                + md.render(f.read_text()))
        (OUT / f"{f.stem}.html").write_text(page(topic, body))
        cards.append(f"<div class=card><a href='{f.stem}.html'>{html.escape(topic)}</a>"
                     f"<div class=meta>{meta}</div></div>")
    intro = ("<h1>Dify Research Agent: reports</h1><p>Generated by a Dify workflow "
             "(SearXNG search + Ollama) running on GitHub Actions. "
             "<a href='https://github.com/dragon28/dify-research-agent'>Source</a>. "
             "Citations point to retrieved sources; they are not fact-checked.</p>")
    (OUT / "index.html").write_text(page("Dify Research Agent reports", intro + "".join(cards)))
    print(f"rendered {len(cards)} reports to {OUT}")


if __name__ == "__main__":
    main()
